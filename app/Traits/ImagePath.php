<?php

namespace App\Traits;

use Illuminate\Support\Facades\Storage;

trait ImagePath
{
    public function getImageAttribute($value): ?string
    {
        if (!$value) {
            return null;
        }

        if (str_starts_with($value, 'http://') || str_starts_with($value, 'https://')) {
            return $value;
        }

        return Storage::disk('public')->url($value);
    }

}
